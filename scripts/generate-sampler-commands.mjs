#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const reserved = new Set(`ids ordered_ids alignas alignof and and_eq asm auto bitand bitor bool break case catch char char8_t char16_t char32_t class compl concept const consteval constexpr constinit const_cast continue co_await co_return co_yield decltype default delete do double dynamic_cast else enum explicit export extern false float for friend goto if inline int long mutable namespace new noexcept not not_eq nullptr operator or or_eq private protected public register reinterpret_cast requires return short signed sizeof static static_assert static_cast struct switch template this thread_local throw true try typedef typeid typename union unsigned using virtual void volatile wchar_t while xor xor_eq`.split(' '));

function generate(source) {
  if (source?.schemaVersion !== 1) throw new Error('schemaVersion must be 1');
  if (!Array.isArray(source.commands) || source.commands.length === 0)
    throw new Error('commands must be a non-empty array');
  const seen = new Set();
  const commands = source.commands.map(id => {
    if (typeof id !== 'string' || !/^[a-z][a-z0-9]*(?:[.-][a-z][a-z0-9]*)*$/.test(id))
      throw new Error(`invalid command ID: ${id}`);
    const slint = id.replaceAll('.', '-'), cpp = id.replaceAll(/[.-]/g, '_');
    if (seen.has(cpp) || reserved.has(cpp)) throw new Error(`duplicate or reserved command name: ${id}`);
    seen.add(cpp);
    return { id, slint, cpp };
  });
  const notice = 'Generated by scripts/generate-sampler-commands.mjs from ui/advanced-sampler/domain/commands.json. Do not edit.';
  return {
    slint: `// ${notice}\nexport global SamplerCommands {\n${commands.map(c => `    out property <string> ${c.slint}: ${JSON.stringify(c.id)};`).join('\n')}\n}\n`,
    cpp: `#pragma once\n// ${notice}\n#include <array>\n#include <string>\n#include <string_view>\n#include <vector>\n\nnamespace dandrum::sampler::commands {\n${commands.map(c => `inline constexpr std::string_view ${c.cpp} = ${JSON.stringify(c.id)};`).join('\n')}\ninline constexpr std::array<std::string_view, ${commands.length}> ordered_ids{\n    ${commands.map(c => c.cpp).join(', ')}\n};\ninline const std::vector<std::string>& ids() {\n    static const std::vector<std::string> values(ordered_ids.begin(), ordered_ids.end());\n    return values;\n}\n} // namespace dandrum::sampler::commands\n`,
  };
}

try {
  const options = { source: path.join(root, 'ui/advanced-sampler/domain/commands.json'),
    slint: path.join(root, 'ui/advanced-sampler/domain/Commands.slint'),
    cpp: path.join(root, 'ui/advanced-sampler/domain/CommandIds.h'), check: false };
  const args = process.argv.slice(2);
  for (let i = 0; i < args.length; ++i) {
    const key = args[i].slice(2);
    if (args[i] === '--check') options.check = true;
    else if (args[i].startsWith('--') && ['source', 'slint', 'cpp'].includes(key) && args[i + 1]) options[key] = path.resolve(args[++i]);
    else throw new Error(`invalid argument ${args[i]}`);
  }
  if (new Set([options.source, options.slint, options.cpp]).size !== 3) throw new Error('source and output paths must be distinct');
  const result = generate(JSON.parse(readFileSync(options.source, 'utf8')));
  for (const key of ['slint', 'cpp']) {
    if (options.check) {
      if (!existsSync(options[key]) || readFileSync(options[key], 'utf8') !== result[key]) {
        process.stderr.write(`${options[key]} is out of date; run node scripts/generate-sampler-commands.mjs\n`);
        process.exitCode = 1;
      }
    } else {
      mkdirSync(path.dirname(options[key]), { recursive: true });
      writeFileSync(options[key], result[key]);
    }
  }
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
}
