#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));

function colour(name, value) {
  if (typeof value === 'string' && /^#[0-9a-f]{6}(?:[0-9a-f]{2})?$/i.test(value)) {
    const rgb = value.slice(1, 7).toUpperCase();
    const alpha = value.length === 9 ? value.slice(7).toUpperCase() : 'FF';
    return { css: value.toUpperCase(), native: `0x${alpha}${rgb}u` };
  }
  const rgba = typeof value === 'string' && value.match(/^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d*\.?\d+)\s*\)$/);
  if (rgba) {
    const [r, g, b, a] = rgba.slice(1).map(Number);
    if (r <= 255 && g <= 255 && b <= 255 && a >= 0 && a <= 1) {
      const hex = [Math.round(a * 255), r, g, b]
        .map(channel => channel.toString(16).padStart(2, '0')).join('').toUpperCase();
      return { css: value, native: `0x${hex}u` };
    }
  }
  throw new Error(`${name}: invalid colour`);
}

function generate(source) {
  if (source.schemaVersion !== 1) throw new Error('schemaVersion must be 1');
  const tokens = source.tokens;
  if (!tokens || typeof tokens !== 'object' || Array.isArray(tokens))
    throw new Error('tokens must be an object');
  const names = Object.keys(tokens).sort();
  for (const name of names)
    if (!/^[a-z]+(?:-[a-z0-9]+)+$/.test(name)) throw new Error(`${name}: invalid token name`);
  const resolved = new Map();
  function resolve(name, trail = []) {
    if (trail.includes(name)) throw new Error(`alias cycle: ${[...trail, name].join(' -> ')}`);
    if (resolved.has(name)) return resolved.get(name);
    const token = tokens[name];
    if (!token || typeof token !== 'object' || Array.isArray(token))
      throw new Error(`${name}: token must be an object`);
    let result;
    if (token.kind === 'alias') {
      if (!Object.hasOwn(tokens, token.value)) throw new Error(`${name}: unknown alias ${token.value}`);
      result = { ...resolve(token.value, [...trail, name]), css: `var(--${token.value})` };
    } else if (token.kind === 'colour') {
      const parsed = colour(name, token.value);
      const argb = parsed.native.slice(2, -1);
      result = { ...parsed, type: 'std::uint32_t', slintType: 'color', slint: parsed.css, legacy: '#' + argb.slice(2) + argb.slice(0, 2) };
    } else if (token.kind === 'number') {
      if (typeof token.value !== 'number' || !Number.isFinite(token.value) || Math.abs(token.value) > 1e6)
        throw new Error(`${name}: invalid number`);
      if (!['', 'px', 'em', 'ms', 's'].includes(token.unit)) throw new Error(`${name}: invalid unit`);
      const text = String(token.value);
      const nativeValue = `${/[.e]/i.test(text) ? text : text + '.0'}f`;
      const duration = token.unit === 'ms' || token.unit === 's';
      const type = duration ? (token.unit === 'ms' ? 'std::chrono::duration<float, std::milli>' : 'std::chrono::duration<float>') : 'float';
      const unit = token.unit === 'px' || duration ? token.unit : '';
      result = { css: text + token.unit, native: duration ? `${type}{${nativeValue}}` : nativeValue, type,
        slintType: duration ? 'duration' : token.unit === 'px' ? 'length' : 'float', slint: text + unit, legacy: text + unit };
    } else if (token.kind === 'text') {
      if (typeof token.value !== 'string' || !token.value.length || /[;{}\u0000-\u001f\u007f]/.test(token.value))
        throw new Error(`${name}: invalid text`);
      // Native renderers select a registered family; CSS keeps its fallback stack.
      const family = name.startsWith('font-') ? token.value.split(',')[0].trim().replace(/^"|"$/g, '') : token.value;
      result = { css: token.value, native: JSON.stringify(token.value), type: 'std::string_view',
        slintType: 'string', slint: JSON.stringify(family), legacy: JSON.stringify(family) };
    } else throw new Error(`${name}: unsupported kind ${token.kind}`);
    resolved.set(name, result);
    return result;
  }
  const entries = names.map(name => [name, resolve(name)]);
  const notice = 'Generated by scripts/generate-ui-tokens.mjs from ui/design-system/tokens.json. Do not edit.';
  const css = `/* ${notice} */\n:root {\n${entries.map(([name, token]) => `  --${name}: ${token.css};`).join('\n')}\n}\n`;
  const cpp = `#pragma once\n// ${notice}\n#include <chrono>\n#include <cstdint>\n#include <string_view>\n\nnamespace dandrum::ui::tokens {\n${entries.map(([name, token]) => `inline constexpr ${token.type} ${name.replaceAll('-', '_')} = ${token.native};`).join('\n')}\n}\n`;
  const sharedCpp = cpp.replace('namespace dandrum::ui::tokens', 'namespace dandrum::slint_ui::tokens');
  const slint = `// ${notice}\n// em tracking is a ratio; multiply by the current font size.\nexport global Tokens {\n${entries.map(([name, token]) => `    out property <${token.slintType}> ${name}: ${token.slint};`).join('\n')}\n}\n`;
  const legacy = `// ${notice}\nexport global DesignTokens {\n${entries.map(([name, token]) => `    out property <${token.slintType}> ${name}: ${token.legacy};`).join('\n')}\n}\n`;
  return { css, cpp, slint, 'shared-cpp': sharedCpp, 'legacy-slint': legacy };
}

try {
  const options = { source: path.join(root, 'ui/design-system/tokens.json'),
    css: path.join(root, 'web/shared/design-tokens.css'),
    cpp: path.join(root, 'src/juce-plugin/DesignTokens.h'),
    slint: path.join(root, 'ui/slint/tokens.slint'),
    'legacy-slint': path.join(root, 'ui/design-system/DesignTokens.slint'), check: false };
  const args = process.argv.slice(2);
  for (let i = 0; i < args.length; ++i) {
    const key = args[i].slice(2);
    if (args[i] === '--check') options.check = true;
    else if (['source', 'css', 'cpp', 'shared-cpp', 'slint', 'legacy-slint'].includes(key) && args[i].startsWith('--') && args[i + 1])
      options[key] = path.resolve(args[++i]);
    else throw new Error(`invalid argument ${args[i]}`);
  }
  // Redirecting C++ output for a fixture keeps the accompanying library output
  // in that same isolated directory. Production includes no JUCE-owned header.
  options['shared-cpp'] ??= options.cpp === path.join(root, 'src/juce-plugin/DesignTokens.h')
    ? path.join(root, 'ui/slint/host/DesignTokens.h') : path.join(path.dirname(options.cpp), 'shared-tokens.h');
  if (new Set([options.source, options.css, options.cpp, options['shared-cpp'], options.slint, options['legacy-slint']]).size !== 6)
    throw new Error('source and output paths must be distinct');
  const result = generate(JSON.parse(readFileSync(options.source, 'utf8')));
  for (const key of ['css', 'cpp', 'shared-cpp', 'slint', 'legacy-slint']) {
    if (options.check) {
      if (!existsSync(options[key]) || readFileSync(options[key], 'utf8') !== result[key]) {
        process.stderr.write(`${options[key]} is out of date; run node scripts/generate-ui-tokens.mjs\n`);
        process.exitCode = 1;
      }
    } else {
      mkdirSync(path.dirname(options[key]), { recursive: true });
      writeFileSync(options[key], result[key]);
    }
  }
} catch (error) {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
}
